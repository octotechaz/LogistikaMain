#!/usr/bin/env node
/**
 * Read active ngrok tunnels and write `.env.ngrok` for external dev testing.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const outFile = path.join(root, ".env.ngrok");

function hostFromUrl(url) {
  return new URL(url).host;
}

async function fetchTunnels() {
  const response = await fetch("http://127.0.0.1:4040/api/tunnels");
  if (!response.ok) {
    throw new Error(`ngrok API returned ${response.status}`);
  }
  const payload = await response.json();
  const byName = new Map();
  for (const tunnel of payload.tunnels || []) {
    const name = tunnel.name;
    const publicUrl = tunnel.public_url || tunnel.url;
    if (name && publicUrl) {
      byName.set(name, publicUrl);
    }
  }
  return byName;
}

const tunnels = await fetchTunnels();
const publicUrl = tunnels.get("public");

if (!publicUrl) {
  const found = [...tunnels.keys()].join(", ") || "(none)";
  throw new Error(
    `Expected ngrok tunnel public. Found: ${found}`
  );
}

const publicHost = hostFromUrl(publicUrl);

const lines = [
  "# Auto-generated by scripts/ngrok-sync-env.mjs — do not commit",
  "NGROK_TUNNEL=1",
  `PUBLIC_SITE_HOST=${publicHost}`,
  `PORTAL_HOST=${publicHost}`,
  `ADMIN_HOST=${publicHost}`,
  "AUTH_COOKIE_DOMAIN=",
  "AUTH_COOKIE_SECURE=true",
  `NEXTAUTH_URL=${publicUrl}`,
  `NEXT_PUBLIC_APP_URL=${publicUrl}`,
  `CORS_ORIGIN=${publicUrl}`,
  "",
];

fs.writeFileSync(outFile, lines.join("\n"), "utf8");

console.log("");
console.log("Ngrok tunellər hazırdır:");
console.log(`  Public : ${publicUrl}`);
console.log(`  Portal : ${publicUrl}`);
console.log(`  Admin  : ${publicUrl}`);
console.log("");
console.log(`Env yazıldı: ${outFile}`);
